#!/usr/bin/env python3
"""Generate reproducible numerical assets for riemann-zeta-function.html.

Displayed zeta zeros and Hardy Z values are computed with mpmath. Prime data are
generated by an exact sieve. Random-matrix spacings use a fixed NumPy seed.
"""

from __future__ import annotations

import colorsys
import json
import math
import os
from datetime import date
from pathlib import Path

os.environ.setdefault("MPLCONFIGDIR", "/tmp/riemann-zeta-matplotlib")

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import mpmath as mp
import numpy as np


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
IMAGES = ROOT / "images"
PAPER = "#fffdf9"
