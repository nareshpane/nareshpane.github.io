const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
let browser;
(async()=>{
  const output=process.argv[2]||'browser-check';fs.mkdirSync(output,{recursive:true});
  browser=await chromium.launch({headless:true,channel:'chrome'});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[],failedRequests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.status()>=400)failedRequests.push([r.status(),r.url()]);});
  const response=await page.goto('http://127.0.0.1:8765/research/giant-components.html',{waitUntil:'networkidle'});
  const pageSha=crypto.createHash('sha256').update(await response.body()).digest('hex');
  await page.waitForFunction(()=>typeof GC!=='undefined'&&GC.demos.length===2);
  const results=[];
  assert.equal(await page.locator('.demo').count(),2);
  assert.equal(await page.locator('.script').count(),15);
  assert.equal(await page.locator('section#snapshot table caption').count(),1);
  assert.equal(await page.locator('mjx-container').count()>20,true,'MathJax rendered equations');
  results.push('MathJax typesetting; both demos; all 15 real Python disclosures');
  for(let index=0;index<2;index++){
    const root=page.locator('.demo').nth(index);
    const action=x=>root.locator(`[data-action="${x}"]`);
    await action('Go to critical').click();
    assert.equal(await root.locator('[data-field="m"]').inputValue(),'30');
    await action('Next Edge').click();assert.equal(await root.locator('[data-field="m"]').inputValue(),'31');
    await action('Previous Edge').click();assert.equal(await root.locator('[data-field="m"]').inputValue(),'30');
    const original=await page.evaluate(i=>JSON.stringify(GC.demos[i].edges),index);
    await root.locator('[data-field="seed"]').fill('2001');await root.locator('[data-field="seed"]').dispatchEvent('change');
    const changed=await page.evaluate(i=>JSON.stringify(GC.demos[i].edges),index);assert.notEqual(changed,original);
    await root.locator('[data-field="seed"]').fill('1993');await action('Generate').click();
    assert.equal(await page.evaluate(i=>JSON.stringify(GC.demos[i].edges),index),original);
    await root.locator('[data-field="speed"]').fill('20');
    await action('Play').click();await page.waitForTimeout(200);await action('Pause').click();
    const stopped=await root.locator('[data-field="m"]').inputValue();assert.ok(Number(stopped)>0);
    await page.waitForTimeout(150);assert.equal(await root.locator('[data-field="m"]').inputValue(),stopped);
    await action('Restart').click();assert.equal(await root.locator('[data-field="m"]').inputValue(),'0');
    await root.locator('[data-field="model"]').selectOption('multigraph');
    await root.locator('[data-field="n"]').fill('200');await action('Generate').click();
    assert.equal(await page.evaluate(i=>GC.demos[i].n,index),200);
    await root.locator('[data-field="timeline"]').fill('100');
    assert.equal(await root.locator('[data-field="m"]').inputValue(),'100');
    assert.ok(await page.evaluate(i=>GC.demos[i].canvas.width>300,index));
    await action('Reset').click();assert.equal(await root.locator('[data-field="n"]').inputValue(),'60');
    assert.equal(await root.locator('[data-field="model"]').inputValue(),'simple');
  }
  results.push('Generate, seed changes/reproduction, critical jump, previous/next, play/pause, restart/reset, timeline, model switch and 200 vertices on both demos');
  // Search seeds deterministically; do not invent an illustrative failure.
  const failureSeed=await page.evaluate(()=>{for(let seed=0;seed<1000;seed++)if(GC.evolution(60,'multigraph',seed).firstFailure!==null)return seed;throw Error('No failure found');});
  const history=page.locator('.demo').nth(1);
  await history.locator('[data-field="model"]').selectOption('multigraph');
  await history.locator('[data-field="seed"]').fill(String(failureSeed));
  await history.locator('[data-action="Generate"]').click();
  const first=await page.evaluate(()=>GC.demos[1].firstFailure);
  await history.locator('[data-field="m"]').fill(String(first-1));await history.locator('[data-field="m"]').dispatchEvent('change');
  await history.locator('[data-field="speed"]').fill('60');await history.locator('[data-action="Play"]').click();await page.waitForTimeout(120);
  assert.equal(await page.evaluate(()=>GC.demos[1].m),first);
  assert.equal(await page.evaluate(()=>GC.demos[1].timer),null);
  assert.ok((await history.locator('.event').innerText()).includes('Historical FAILURE'));
  await page.evaluate(()=>GC.demos[1].seek(GC.demos[1].edges.length));
  assert.equal(await page.evaluate(()=>GC.demos[1].d.complex),1);
  assert.ok((await history.locator('.event').innerText()).includes('Historical FAILURE'));
  await page.evaluate(()=>GC.demos[1].seek(GC.demos[1].firstFailure-1));
  assert.ok(!(await history.locator('.event').innerText()).includes('FAILURE'));
  results.push(`Multigraph seed ${failureSeed}: auto-pause at edge ${first}; historical failure persists after final merger, and backward navigation recomputes the correct prefix`);
  await page.locator('.demo').nth(0).locator('[data-action="Go to critical"]').click();
  const shapeCheck=await page.evaluate(()=>GC.demos[0].d.p.map((_,i)=>GC.demos[0].d.beta(i)));
  assert.ok(shapeCheck.every(b=>b>=0));
  await page.locator('section#snapshot .demo').screenshot({path:path.join(output,'critical-snapshot.png')});
  await page.locator('header.hero').scrollIntoViewIfNeeded();await page.screenshot({path:path.join(output,'article-desktop.png')});
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(150);
  const overflow=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));assert.ok(overflow.scroll<=overflow.width,JSON.stringify(overflow));
  await page.screenshot({path:path.join(output,'article-mobile.png')});
  await page.locator('.demo').nth(0).screenshot({path:path.join(output,'demo-mobile.png')});
  const assetsMissing=failedRequests.filter(([,url])=>url.startsWith('http://127.0.0.1:8765/research/giant-component-1993'));
  assert.deepEqual(assetsMissing,[]);assert.deepEqual(errors,[]);
  results.push('390px mobile resize: no page-wide horizontal overflow; canvas redraw; no JS errors or missing local assets');
  await page.setViewportSize({width:320,height:700});await page.waitForTimeout(100);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  const disclosure=page.locator('.script').first();await disclosure.locator('summary').click();
  await disclosure.locator('.copy').click();
  await page.waitForFunction(()=>document.querySelector('.script .copy').textContent==='Copied');
  assert.equal(await disclosure.locator('.copy').innerText(),'Copied');
  assert.equal((await page.evaluate(()=>navigator.clipboard.readText())).replace(/\r\n/g,'\n'),await disclosure.locator('code').innerText());
  results.push('320px viewport has no page-wide overflow; accessible source disclosure and clipboard copy verified');
  const report={passed:true,page_sha256:pageSha,checks:results,errors,failedRequests,mathjaxContainers:await page.locator('mjx-container').count(),failureSeed,firstFailure:first};
  fs.writeFileSync(path.join(output,'browser-validation.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));await browser.close();
})().catch(async e=>{console.error(e);if(browser)await browser.close();process.exitCode=1;});
